CMP_BINARY = 0
CMP_ASCII = 1

_PKDCL_END = 0x305
_PKDCL_ERR = 0x306


_NATIVE_SOUND = [None]


def _native_sound():
    if _NATIVE_SOUND[0] is None:
        try:
            import os
            here = os.path.dirname(os.path.abspath(__file__))
            import mpqcrypt
            _NATIVE_SOUND[0] = mpqcrypt.load_explode() or False
        except Exception:
            _NATIVE_SOUND[0] = False
    return _NATIVE_SOUND[0]


class PKWareError(ValueError):
    pass


def _gen_decode_tabs(start_indexes, length_bits):
    positions = bytearray(0x100)
    for i in range(len(start_indexes)):
        length = 1 << length_bits[i]
        for index in range(start_indexes[i], 0x100, length):
            positions[index] = i
    return bytes(positions)


def _gen_asc_tabs():
    bits_asc = bytearray(CH_BITS_ASC)
    c34 = bytearray(0x100)
    d34 = bytearray(0x100)
    e34 = bytearray(0x80)
    eb4 = bytearray(0x100)

    for count in range(0xFF, -1, -1):
        code = CH_CODE_ASC[count]
        b = bits_asc[count]

        if b <= 8:
            add = 1 << b
            acc = code
            while acc < 0x100:
                c34[acc] = count
                acc += add
        elif (code & 0xFF) != 0:
            c34[code & 0xFF] = 0xFF
            if code & 0x3F:
                b -= 4
                bits_asc[count] = b
                add = 1 << b
                acc = code >> 4
                while acc < 0x100:
                    d34[acc] = count
                    acc += add
            else:
                b -= 6
                bits_asc[count] = b
                add = 1 << b
                acc = code >> 6
                while acc < 0x80:
                    e34[acc] = count
                    acc += add
        else:
            b -= 8
            bits_asc[count] = b
            add = 1 << b
            acc = code >> 8
            while acc < 0x100:
                eb4[acc] = count
                acc += add

    return bytes(bits_asc), bytes(c34), bytes(d34), bytes(e34), bytes(eb4)


def explode(data, expected=None, max_out=None):
    if expected is not None and max_out is None:
        native = _NATIVE_SOUND[0] if _NATIVE_SOUND[0] is not None else _native_sound()
        if native:
            r = native(data, expected)
            if r is not None:
                return r
    if not data:
        raise PKWareError('empty implode stream')
    if len(data) <= 4:
        raise PKWareError('implode stream too short (%d bytes)' % len(data))

    if data[0] == 0x08 and data[1] in (CMP_BINARY, CMP_ASCII):
        data = data[1:]

    if max_out is None:
        max_out = (expected + 0x10000) if expected else (64 << 20)

    ctype = data[0]
    dsize_bits = data[1]
    if dsize_bits < 4 or dsize_bits > 6:
        raise PKWareError('invalid dictionary size: %d' % dsize_bits)

    dsize_mask = 0xFFFF >> (0x10 - dsize_bits)

    length_codes = _gen_decode_tabs(LEN_CODE, LEN_BITS)
    dist_pos_codes = _gen_decode_tabs(DIST_CODE, DIST_BITS)

    if ctype == CMP_ASCII:
        ch_bits_asc, offs_c34, offs_d34, offs_e34, offs_eb4 = _gen_asc_tabs()
    elif ctype == CMP_BINARY:
        ch_bits_asc = None
        offs_c34 = offs_d34 = offs_e34 = offs_eb4 = None
    else:
        raise PKWareError('invalid compression mode: %d' % ctype)

    n_bytes = len(data)
    in_pos = 3
    bit_buff = data[2]
    extra_bits = 0

    def waste(nbits):
        nonlocal in_pos, bit_buff, extra_bits
        if nbits <= extra_bits:
            extra_bits -= nbits
            bit_buff >>= nbits
            return False
        bit_buff >>= extra_bits
        if in_pos >= n_bytes:
            extra_bits = 0
            bit_buff = 0
            return True
        bit_buff |= data[in_pos] << 8
        in_pos += 1
        bit_buff >>= (nbits - extra_bits)
        extra_bits = (extra_bits - nbits) + 8
        return False

    def decode_lit():
        if bit_buff & 1:
            if waste(1):
                return _PKDCL_ERR
            length_code = length_codes[bit_buff & 0xFF]
            if waste(LEN_BITS[length_code]):
                return _PKDCL_ERR
            extra_length_bits = EX_LEN_BITS[length_code]
            if extra_length_bits:
                extra_length = bit_buff & ((1 << extra_length_bits) - 1)
                if waste(extra_length_bits):
                    if (length_code + extra_length) != 0x10E:
                        return _PKDCL_ERR
                length_code = LEN_BASE[length_code] + extra_length
            return length_code + 0x100

        if waste(1):
            return _PKDCL_ERR

        if ctype == CMP_BINARY:
            value = bit_buff & 0xFF
            if waste(8):
                return _PKDCL_ERR
            return value

        if bit_buff & 0xFF:
            value = offs_c34[bit_buff & 0xFF]
            if value == 0xFF:
                if bit_buff & 0x3F:
                    if waste(4):
                        return _PKDCL_ERR
                    value = offs_d34[bit_buff & 0xFF]
                else:
                    if waste(6):
                        return _PKDCL_ERR
                    value = offs_e34[bit_buff & 0x7F]
        else:
            if waste(8):
                return _PKDCL_ERR
            value = offs_eb4[bit_buff & 0xFF]

        if waste(ch_bits_asc[value]):
            return _PKDCL_ERR
        return value

    def decode_dist(rep_length):
        dist_pos_code = dist_pos_codes[bit_buff & 0xFF]
        dist_pos_bits = DIST_BITS[dist_pos_code]
        if waste(dist_pos_bits):
            return 0
        if rep_length == 2:
            distance = (dist_pos_code << 2) | (bit_buff & 0x03)
            if waste(2):
                return 0
        else:
            distance = (dist_pos_code << dsize_bits) | (bit_buff & dsize_mask)
            if waste(dsize_bits):
                return 0
        return distance + 1

    out = bytearray()
    target_len = expected
    empty = True
    err = None

    while True:
        next_literal = decode_lit()
        if next_literal == _PKDCL_ERR:
            if empty:
                break
            if target_len is None:
                err = 'corrupt implode stream (DecodeLit)'
            break
        if next_literal == _PKDCL_END:
            break

        if next_literal >= 0x100:
            rep_length = next_literal - 0xFE
            minus_dist = decode_dist(rep_length)
            if minus_dist == 0:
                raise PKWareError('corrupt implode stream (DecodeDist)')
            if minus_dist > len(out):
                raise PKWareError('distance %d greater than the output (%d bytes)'
                                  % (minus_dist, len(out)))
            src = len(out) - minus_dist
            for _ in range(rep_length):
                out.append(out[src])
                src += 1
        else:
            out.append(next_literal)

        if target_len is not None and len(out) >= target_len:
            return bytes(out[:target_len])
        if len(out) > max_out:
            raise PKWareError('output went past the limit of %d bytes (not an implode stream?)'
                              % max_out)
        empty = False

    if err:
        raise PKWareError(err)

    if target_len is not None and len(out) < target_len:
        raise PKWareError('short output: %d bytes, expected %d' % (len(out), target_len))
    if target_len is not None:
        return bytes(out[:target_len])
    return bytes(out)


def decompress(data, expected=None):
    return explode(data, expected=expected)


def has_mask(data):
    return len(data) > 2 and data[0] == 0x08 and data[1] in (CMP_BINARY, CMP_ASCII)


def is_implode(data):
    if has_mask(data):
        return True
    return len(data) > 3 and data[0] in (CMP_BINARY, CMP_ASCII) and 4 <= data[1] <= 6

_ITEMS = 515
_HEAD = _ITEMS
_NULL = -1
_AFTER, _BEFORE = 1, 2
_END = 0x100
_NEW_BYTE = 0x101
_ERROR = 0x1FF
BITS = 10
STABLE = 64
_LONG = -1


class _Tree(object):
    def __init__(self):
        n = _ITEMS + 1
        self.next_item = [_NULL] * n
        self.prev_item = [_NULL] * n
        self.field_value = [0] * n
        self.weight = [0] * n
        self.parent = [_NULL] * n
        self.child = [_NULL] * n
        self.in_use = 0
        self.by_byte = [_NULL] * 258
        self.next_item[_HEAD] = self.prev_item[_HEAD] = _HEAD
        self.min_valid = 1

    def _remove(self, i):
        next_item, prev_item = self.next_item, self.prev_item
        if next_item[i] != _NULL:
            a, p = prev_item[i], next_item[i]
            next_item[a] = p
            prev_item[p] = a
            next_item[i] = prev_item[i] = _NULL

    def _link(self, a, b):
        next_item, prev_item = self.next_item, self.prev_item
        n = next_item[a]
        next_item[b] = n
        prev_item[b] = prev_item[n]
        prev_item[n] = b
        next_item[a] = b

    def _insert(self, i, where, point=_NULL):
        self._remove(i)
        if point == _NULL:
            point = _HEAD
        if where == _AFTER:
            self._link(point, i)
        elif where == _BEFORE:
            self._link(self.prev_item[point], i)

    def _higher_or_equal(self, i, weight):
        if i != _NULL:
            weights, prev_item = self.weight, self.prev_item
            while i != _HEAD:
                if weights[i] >= weight:
                    return i
                i = prev_item[i]
        return _HEAD

    def _create(self, field_value, weight, where):
        if self.in_use >= _ITEMS:
            return _NULL
        i = self.in_use
        self.in_use += 1
        self._insert(i, where)
        self.field_value[i] = field_value
        self.weight[i] = weight
        self.parent[i] = _NULL
        self.child[i] = _NULL
        return i

    def _reposition(self, i, max_weight):
        if self.weight[i] < max_weight:
            larger = self._higher_or_equal(self.prev_item[_HEAD], self.weight[i])
            self._remove(i)
            self._link(larger, i)
            return max_weight
        return self.weight[i]

    def assemble(self, type_name):
        self.by_byte = [_NULL] * 258
        max_weight = 0
        type_name &= 0x0F
        if type_name >= len(WEIGHTS):
            return False
        table = WEIGHTS[type_name]
        for b in range(0x100):
            if table[b]:
                i = self._create(b, table[b], _AFTER)
                self.by_byte[b] = i
                max_weight = self._reposition(i, max_weight)
        self.by_byte[_END] = self._create(_END, 1, _BEFORE)
        self.by_byte[_NEW_BYTE] = self._create(_NEW_BYTE, 1, _BEFORE)
        lo = self.prev_item[_HEAD]
        while lo != _HEAD:
            hi = self.prev_item[lo]
            if hi == _HEAD:
                break
            new = self._create(0, self.weight[hi] + self.weight[lo], _AFTER)
            if new == _NULL:
                return False
            self.parent[lo] = new
            self.parent[hi] = new
            self.child[new] = lo
            max_weight = self._reposition(new, max_weight)
            lo = self.prev_item[hi]
        self.min_valid = 1
        return True

    def increment(self, i):
        weight, parent, child, next_item = self.weight, self.parent, self.child, self.next_item
        while i != _NULL:
            weight[i] += 1
            larger = self._higher_or_equal(self.prev_item[i], weight[i])
            hi = next_item[larger]
            if hi != i:
                if parent[hi] == _NULL or parent[i] == _NULL:
                    raise WaveError('huffman: the tree degenerated (swap with the root)')
                self._remove(hi)
                self._link(i, hi)
                self._remove(i)
                self._link(larger, i)
                lo = child[parent[hi]]
                p = parent[i]
                if child[p] == i:
                    child[p] = hi
                if lo == hi:
                    child[parent[hi]] = i
                p = parent[i]
                parent[i] = parent[hi]
                parent[hi] = p
                self.min_valid += 1
            i = parent[i]

    def new_branch(self, v1, v2):
        last = self.prev_item[_HEAD]
        hi = self._create(v1, self.weight[last], _BEFORE)
        if hi == _NULL:
            return False
        self.parent[hi] = last
        self.by_byte[v1] = hi
        lo = self._create(v2, 0, _BEFORE)
        if lo == _NULL:
            return False
        self.parent[lo] = last
        self.child[last] = lo
        self.by_byte[v2] = lo
        self.increment(lo)
        return True


def _table(tree, bits=BITS):
    child, prev_item, field_value, next_item = tree.child, tree.prev_item, tree.field_value, tree.next_item
    tab = [_LONG] * (1 << bits)
    root = next_item[_HEAD]
    if root == _HEAD:
        return tab
    stack = [(root, 0, 0)]
    while stack:
        i, code_part, n = stack.pop()
        lo = child[i]
        if lo == _NULL:
            if n <= bits:
                e = field_value[i] | (n << 12)
                tab[code_part::(1 << n)] = [e] * ((1 << bits) >> n)
            continue
        n += 1
        if n <= bits:
            stack.append((lo, code_part, n))
            stack.append((prev_item[lo], code_part | (1 << (n - 1)), n))
    return tab


def decompress_huffman(data_bytes, ceiling=None):
    if ceiling is not None and ceiling <= 0:
        raise WaveError('huffman: output buffer of %r bytes' % ceiling)
    data_bytes = bytes(data_bytes)
    native = _NATIVE_SOUND[0] if _NATIVE_SOUND[0] is not None else _native_sound()
    if native and ceiling is not None:
        r = native[0](data_bytes, ceiling)
        if r is not None:
            return r
    n = len(data_bytes)
    if n < 1:
        raise WaveError('huffman: empty stream (the type byte is missing)')
    type_name = data_bytes[0]
    pos, buf, nb = 1, 0, 0
    sparse_data = (type_name == 0)
    tree = _Tree()
    if not tree.assemble(type_name):
        raise WaveError('huffman: data type 0x%02x has no table (0..8)' % type_name)
    next_item, prev_item, child, field_value = tree.next_item, tree.prev_item, tree.child, tree.field_value
    out_limit = ceiling if ceiling is not None else -1
    out = bytearray()
    tab = None
    since = 0
    bitmask = (1 << BITS) - 1
    while True:
        v = _LONG
        if tab is not None:
            while nb < BITS and pos < n:
                buf |= data_bytes[pos] << nb
                pos += 1
                nb += 8
            if nb >= BITS:
                e = tab[buf & bitmask]
                if e >= 0:
                    q = e >> 12
                    buf >>= q
                    nb -= q
                    v = e & 0xFFF
                    if v < 0x100:
                        if len(out) == out_limit:
                            break
                        out.append(v)
                        continue
        if v < 0:
            it = next_item[_HEAD]
            v = _ERROR
            if it != _HEAD:
                lo = child[it]
                while lo != _NULL:
                    if nb == 0:
                        if pos >= n:
                            it = _NULL
                            break
                        buf = data_bytes[pos]
                        pos += 1
                        nb = 8
                    it = prev_item[lo] if buf & 1 else lo
                    buf >>= 1
                    nb -= 1
                    lo = child[it]
                if it != _NULL:
                    v = field_value[it]
        if v == _END:
            break
        if v == _ERROR:
            raise WaveError('huffman: the stream ended before the end code (%d bytes, %d decoded)' % (n, len(out)))
        if v == _NEW_BYTE:
            if nb < 8:
                if pos >= n:
                    raise WaveError('huffman: the stream ended in the middle of a new byte')
                buf |= data_bytes[pos] << nb
                pos += 1
                nb += 8
            v = buf & 0xFF
            buf >>= 8
            nb -= 8
            if not tree.new_branch(field_value[prev_item[_HEAD]], v):
                raise WaveError('huffman: the tree is full (%d items)' % _ITEMS)
            if not sparse_data:
                tree.increment(tree.by_byte[v])
                tab = None
                since = 0
        if len(out) == out_limit:
            break
        out.append(v & 0xFF)
        if sparse_data:
            tree.increment(tree.by_byte[v])
        else:
            since += 1
            if tab is None and since >= STABLE:
                tab = _table(tree, BITS)
    return bytes(out)


NEXT_STEP = (
    -1, 0, -1, 4, -1, 2, -1, 6,
    -1, 1, -1, 5, -1, 3, -1, 7,
    -1, 1, -1, 5, -1, 3, -1, 7,
    -1, 2, -1, 4, -1, 6, -1, 8,
)
STEP_SIZE = (
    7, 8, 9, 10, 11, 12, 13, 14,
    16, 17, 19, 21, 23, 25, 28, 31,
    34, 37, 41, 45, 50, 55, 60, 66,
    73, 80, 88, 97, 107, 118, 130, 143,
    157, 173, 190, 209, 230, 253, 279, 307,
    337, 371, 408, 449, 494, 544, 598, 658,
    724, 796, 876, 963, 1060, 1166, 1282, 1411,
    1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024,
    3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484,
    7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899,
    15289, 16818, 18500, 20350, 22385, 24623, 27086, 29794,
    32767,
)
INITIAL_INDEX = 0x2C
MAX_CHANNELS = 2


def decompress_adpcm(data_bytes, channels, ceiling=None):
    if channels < 1 or channels > MAX_CHANNELS:
        raise WaveError('adpcm: %r channels (1 or 2)' % (channels,))
    data_bytes = bytes(data_bytes)
    native = _NATIVE_SOUND[0] if _NATIVE_SOUND[0] is not None else _native_sound()
    if native and ceiling is not None and ceiling >= 0:
        r = native[1](data_bytes, channels, ceiling)
        if r is not None:
            return r
    n = len(data_bytes)
    max_samples = (ceiling // 2) if ceiling is not None else n * 2 + channels
    samples = array('h')
    if n < 2:
        return b''
    shift = data_bytes[1] & 0x1F
    predicted = [0] * MAX_CHANNELS
    index_ = [INITIAL_INDEX] * MAX_CHANNELS
    pos = 2
    for c in range(channels):
        if pos + 2 > n or len(samples) >= max_samples:
            return _pcm(samples)
        s = data_bytes[pos] | (data_bytes[pos + 1] << 8)
        if s >= 0x8000:
            s -= 0x10000
        pos += 2
        predicted[c] = s
        samples.append(s)
    c = channels - 1
    steps, next_steps = STEP_SIZE, NEXT_STEP
    while pos < n:
        e = data_bytes[pos]
        pos += 1
        c = (c + 1) % channels
        if e == 0x80:
            if index_[c]:
                index_[c] -= 1
            if len(samples) >= max_samples:
                break
            samples.append(predicted[c])
        elif e == 0x81:
            index_[c] = min(index_[c] + 8, 0x58)
            c = (c + 1) % channels
        else:
            i = index_[c]
            step = steps[i]
            d = step >> shift
            if e & 0x01:
                d += step
            if e & 0x02:
                d += step >> 1
            if e & 0x04:
                d += step >> 2
            if e & 0x08:
                d += step >> 3
            if e & 0x10:
                d += step >> 4
            if e & 0x20:
                d += step >> 5
            p = predicted[c]
            if e & 0x40:
                p -= d
                if p <= -32768:
                    p = -32768
            else:
                p += d
                if p >= 32767:
                    p = 32767
            predicted[c] = p
            if len(samples) >= max_samples:
                break
            samples.append(p)
            i += next_steps[e & 0x1F]
            index_[c] = 0 if i < 0 else (88 if i > 88 else i)
    return _pcm(samples)


def _pcm(samples):
    if sys.byteorder != 'little':
        samples.byteswap()
    return samples.tobytes()


ORDER = (
    (0x10, 'bzip2'),
    (0x08, 'pkware'),
    (0x02, 'zlib'),
    (0x01, 'huffman'),
    (0x80, 'adpcm stereo'),
    (0x40, 'adpcm mono'),
    (0x20, 'sparse'),
)
_KNOWN = sum(bit for bit, _ in ORDER)


def decompress_sector_chain(sector_bytes, expected_len=None):
    sector_bytes = bytes(sector_bytes)
    if expected_len is not None:
        if len(sector_bytes) == expected_len:
            return sector_bytes
        if len(sector_bytes) > expected_len:
            raise WaveError('sector of %d bytes, larger than the %d expected' % (len(sector_bytes), expected_len))
    if not sector_bytes:
        raise WaveError('empty sector')
    bitmask = sector_bytes[0]
    steps = [(bit, fname) for bit, fname in ORDER if bitmask & bit]
    if not steps or bitmask & ~_KNOWN:
        raise WaveError('mask 0x%02x not supported (known bits: 0x%02x)' % (bitmask, _KNOWN))
    if bitmask & 0x20:
        raise WaveError('mask 0x%02x: sparse (0x20) not implemented here' % bitmask)
    data_bytes = sector_bytes[1:]
    ceiling = expected_len if expected_len is not None else CAP_WITHOUT_EXPECTED
    for k, (bit, fname) in enumerate(steps):
        last = k == len(steps) - 1
        try:
            if bit == 0x10:
                d = bz2.BZ2Decompressor()
                data_bytes = d.decompress(data_bytes, ceiling + 1)
                if len(data_bytes) > ceiling:
                    data_bytes, rest = data_bytes[:ceiling], 0
                    while not d.eof:
                        if d.needs_input:
                            raise WaveError('bzip2 (mask 0x%02x): the stream ends before its end' % bitmask)
                        rest += len(d.decompress(b'', 1 << 20))
                        if rest > CAP_WITHOUT_EXPECTED:
                            raise WaveError('bzip2 (mask 0x%02x): the stream goes %d MB past the sector'
                                            % (bitmask, CAP_WITHOUT_EXPECTED >> 20))
                elif not d.eof:
                    raise WaveError('bzip2 (mask 0x%02x): the stream ends before its end' % bitmask)
            elif bit == 0x08:
                import pkware
                data_bytes = pkware.decompress(data_bytes, expected=expected_len if last else None)
                if expected_len is not None:
                    data_bytes = data_bytes[:expected_len]
            elif bit == 0x02:
                d = zlib.decompressobj()
                data_bytes = d.decompress(data_bytes, ceiling + 1)
                if len(data_bytes) > ceiling:
                    raise WaveError('zlib: more bytes than the %d of the sector' % ceiling)
                if not d.eof:
                    raise WaveError('zlib (mask 0x%02x): the stream ends before its end' % bitmask)
            elif bit == 0x01:
                data_bytes = decompress_huffman(data_bytes, expected_len)
            elif bit == 0x80:
                data_bytes = decompress_adpcm(data_bytes, 2, expected_len)
            elif bit == 0x40:
                data_bytes = decompress_adpcm(data_bytes, 1, expected_len)
        except WaveError:
            raise
        except (zlib.error, OSError, EOFError, ValueError) as e:
            raise WaveError('%s (mask 0x%02x): %s' % (fname, bitmask, e))
        if not data_bytes:
            raise WaveError('%s (mask 0x%02x) returned 0 bytes: corrupted sector' % (fname, bitmask))
    return data_bytes
